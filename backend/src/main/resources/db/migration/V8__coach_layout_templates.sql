CREATE TABLE coach_layout_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_code VARCHAR(40) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    class_code VARCHAR(8) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_coach_layout_template_code UNIQUE(template_code)
);

CREATE TABLE coach_layout_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    seat_type VARCHAR(20) NOT NULL,
    position_index INTEGER NOT NULL,
    CONSTRAINT fk_coach_layout_slot_template FOREIGN KEY(template_id) REFERENCES coach_layout_templates(id),
    CONSTRAINT uk_coach_layout_slot_number UNIQUE(template_id, seat_number),
    CONSTRAINT uk_coach_layout_slot_position UNIQUE(template_id, position_index),
    CONSTRAINT ck_coach_layout_slot_type CHECK(seat_type IN ('LOWER','MIDDLE','UPPER','SIDE_LOWER','SIDE_UPPER','WINDOW','AISLE','CHAIR'))
);
CREATE INDEX idx_coach_layout_slots_template ON coach_layout_slots(template_id, position_index);

ALTER TABLE coaches ADD COLUMN layout_template_id BIGINT;
ALTER TABLE coaches ADD CONSTRAINT fk_coaches_layout_template FOREIGN KEY(layout_template_id) REFERENCES coach_layout_templates(id);
CREATE INDEX idx_coaches_layout_template ON coaches(layout_template_id);

