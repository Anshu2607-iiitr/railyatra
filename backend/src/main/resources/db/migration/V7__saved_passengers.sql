CREATE TABLE saved_passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    full_name VARCHAR(140) NOT NULL,
    age INTEGER NOT NULL,
    gender VARCHAR(20) NOT NULL,
    berth_preference VARCHAR(30) NOT NULL DEFAULT 'NO_PREFERENCE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_saved_passenger_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_saved_passenger_age CHECK (age BETWEEN 1 AND 125),
    CONSTRAINT ck_saved_passenger_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT ck_saved_passenger_berth CHECK (berth_preference IN ('NO_PREFERENCE', 'LOWER', 'MIDDLE', 'UPPER', 'SIDE_LOWER', 'SIDE_UPPER'))
);

CREATE INDEX idx_saved_passengers_user ON saved_passengers(user_id, id);
