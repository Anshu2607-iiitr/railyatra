CREATE TABLE stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_code VARCHAR(10) NOT NULL,
    station_name VARCHAR(160) NOT NULL,
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_stations_station_code UNIQUE (station_code)
);
CREATE INDEX idx_stations_station_code ON stations (station_code);

CREATE TABLE trains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_number VARCHAR(10) NOT NULL,
    train_name VARCHAR(160) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_trains_train_number UNIQUE (train_number)
);
CREATE INDEX idx_trains_train_number ON trains (train_number);

CREATE TABLE train_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT NOT NULL,
    runs_on VARCHAR(7) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    CONSTRAINT fk_train_schedules_train FOREIGN KEY (train_id) REFERENCES trains(id),
    CONSTRAINT uk_train_schedules_train_effective_from UNIQUE (train_id, effective_from)
);
CREATE INDEX idx_train_schedules_train_id ON train_schedules (train_id);

CREATE TABLE train_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT NOT NULL,
    station_id BIGINT NOT NULL,
    stop_sequence INTEGER NOT NULL,
    arrival_time TIME,
    departure_time TIME,
    day_offset INTEGER NOT NULL DEFAULT 0,
    distance_km INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_train_stops_train FOREIGN KEY (train_id) REFERENCES trains(id),
    CONSTRAINT fk_train_stops_station FOREIGN KEY (station_id) REFERENCES stations(id),
    CONSTRAINT uk_train_stops_train_sequence UNIQUE (train_id, stop_sequence),
    CONSTRAINT uk_train_stops_train_station UNIQUE (train_id, station_id),
    CONSTRAINT ck_train_stops_sequence CHECK (stop_sequence > 0),
    CONSTRAINT ck_train_stops_day_offset CHECK (day_offset >= 0)
);
CREATE INDEX idx_train_stops_train_id ON train_stops (train_id);
CREATE INDEX idx_train_stops_station_id ON train_stops (station_id);
CREATE INDEX idx_train_stops_train_sequence ON train_stops (train_id, stop_sequence);

CREATE TABLE train_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT NOT NULL,
    class_code VARCHAR(8) NOT NULL,
    class_name VARCHAR(80) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_train_classes_train FOREIGN KEY (train_id) REFERENCES trains(id),
    CONSTRAINT uk_train_classes_train_code UNIQUE (train_id, class_code)
);
CREATE INDEX idx_train_classes_train_id ON train_classes (train_id);

CREATE TABLE coaches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_class_id BIGINT NOT NULL,
    coach_code VARCHAR(10) NOT NULL,
    coach_position INTEGER NOT NULL,
    CONSTRAINT fk_coaches_train_class FOREIGN KEY (train_class_id) REFERENCES train_classes(id),
    CONSTRAINT uk_coaches_train_class_code UNIQUE (train_class_id, coach_code),
    CONSTRAINT uk_coaches_train_class_position UNIQUE (train_class_id, coach_position)
);
CREATE INDEX idx_coaches_train_class_id ON coaches (train_class_id);

CREATE TABLE seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coach_id BIGINT NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    berth_type VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_seats_coach FOREIGN KEY (coach_id) REFERENCES coaches(id),
    CONSTRAINT uk_seats_coach_number UNIQUE (coach_id, seat_number)
);
CREATE INDEX idx_seats_coach_id ON seats (coach_id);

CREATE TABLE fare_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT NOT NULL,
    train_class_id BIGINT NOT NULL,
    origin_station_id BIGINT NOT NULL,
    destination_station_id BIGINT NOT NULL,
    base_fare DECIMAL(12,2) NOT NULL,
    per_km_fare DECIMAL(12,4) NOT NULL,
    minimum_fare DECIMAL(12,2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_fare_rules_train FOREIGN KEY (train_id) REFERENCES trains(id),
    CONSTRAINT fk_fare_rules_class FOREIGN KEY (train_class_id) REFERENCES train_classes(id),
    CONSTRAINT fk_fare_rules_origin FOREIGN KEY (origin_station_id) REFERENCES stations(id),
    CONSTRAINT fk_fare_rules_destination FOREIGN KEY (destination_station_id) REFERENCES stations(id),
    CONSTRAINT uk_fare_rules_segment UNIQUE (train_id, train_class_id, origin_station_id, destination_station_id),
    CONSTRAINT ck_fare_rules_different_stations CHECK (origin_station_id <> destination_station_id)
);
CREATE INDEX idx_fare_rules_train_id ON fare_rules (train_id);
CREATE INDEX idx_fare_rules_origin_station_id ON fare_rules (origin_station_id);
CREATE INDEX idx_fare_rules_destination_station_id ON fare_rules (destination_station_id);
