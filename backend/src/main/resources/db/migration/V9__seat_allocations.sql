CREATE TABLE seat_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_inventory_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    allocation_reference VARCHAR(80) NOT NULL,
    passenger_index INTEGER NOT NULL,
    requested_berth VARCHAR(30) NOT NULL,
    allocated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMP,
    CONSTRAINT fk_seat_allocation_inventory FOREIGN KEY(seat_inventory_id) REFERENCES seat_inventories(id),
    CONSTRAINT fk_seat_allocation_seat FOREIGN KEY(seat_id) REFERENCES seats(id),
    CONSTRAINT uk_seat_allocation_inventory_seat UNIQUE(seat_inventory_id, seat_id),
    CONSTRAINT uk_seat_allocation_reference_passenger UNIQUE(allocation_reference, passenger_index),
    CONSTRAINT ck_seat_allocation_passenger_index CHECK(passenger_index >= 0),
    CONSTRAINT ck_seat_allocation_berth CHECK(requested_berth IN ('NO_PREFERENCE','LOWER','MIDDLE','UPPER','SIDE_LOWER','SIDE_UPPER'))
);
CREATE INDEX idx_seat_allocations_inventory ON seat_allocations(seat_inventory_id, released_at);
CREATE INDEX idx_seat_allocations_reference ON seat_allocations(allocation_reference);
