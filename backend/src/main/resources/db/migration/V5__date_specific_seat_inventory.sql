CREATE TABLE seat_inventories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  train_id BIGINT NOT NULL,
  journey_date DATE NOT NULL,
  train_class_id BIGINT NOT NULL,
  quota VARCHAR(30) NOT NULL,
  total_capacity INTEGER NOT NULL,
  available_count INTEGER NOT NULL,
  rac_capacity INTEGER NOT NULL,
  rac_available_count INTEGER NOT NULL,
  waiting_list_count INTEGER NOT NULL DEFAULT 0,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_inventory_train FOREIGN KEY(train_id) REFERENCES trains(id),
  CONSTRAINT fk_inventory_class FOREIGN KEY(train_class_id) REFERENCES train_classes(id),
  CONSTRAINT uk_inventory_identity UNIQUE(train_id,journey_date,train_class_id,quota),
  CONSTRAINT ck_inventory_counts CHECK(total_capacity>=0 AND available_count>=0 AND rac_capacity>=0 AND rac_available_count>=0 AND waiting_list_count>=0)
);
CREATE INDEX idx_inventory_train_date_class ON seat_inventories(train_id,journey_date,train_class_id,quota);
