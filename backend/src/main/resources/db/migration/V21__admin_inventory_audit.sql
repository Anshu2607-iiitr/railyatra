CREATE TABLE inventory_adjustment_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inventory_id BIGINT NOT NULL REFERENCES seat_inventories(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 request_key VARCHAR(80) NOT NULL,
 reason VARCHAR(500) NOT NULL,
 expected_version BIGINT NOT NULL,
 requested_capacity INTEGER NOT NULL,
 requested_rac_capacity INTEGER NOT NULL,
 before_snapshot TEXT NOT NULL,
 after_snapshot TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uk_inventory_adjustment_retry UNIQUE(inventory_id,actor_id,request_key)
);
CREATE INDEX idx_inventory_audit_history ON inventory_adjustment_audit(inventory_id,id);
CREATE INDEX idx_hold_inventory_status_type ON seat_holds(inventory_id,status,reservation_type);
CREATE INDEX idx_booking_hold_status ON bookings(hold_id,current_status);
