CREATE TABLE booking_status_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 internal_reference VARCHAR(32) NOT NULL,
 event_type VARCHAR(40) NOT NULL,
 delivery_id BIGINT UNIQUE,
 created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_status_event_user_reference_id ON booking_status_events(user_id, internal_reference, delivery_id);
CREATE INDEX idx_status_event_user_id ON booking_status_events(user_id,delivery_id);
CREATE INDEX idx_status_event_pending ON booking_status_events(delivery_id,id);
CREATE TABLE booking_event_delivery_clock(id INTEGER PRIMARY KEY CHECK(id=1),last_sequence BIGINT NOT NULL);
