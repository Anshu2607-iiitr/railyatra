CREATE TABLE bookings (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    hold_id VARCHAR(36) NOT NULL,
    train_id BIGINT NOT NULL,
    train_class_id BIGINT NOT NULL,
    origin_station_id BIGINT NOT NULL,
    destination_station_id BIGINT NOT NULL,
    journey_date DATE NOT NULL,
    quota VARCHAR(30) NOT NULL,
    internal_booking_reference VARCHAR(32) NOT NULL,
    provider_pnr VARCHAR(64),
    provider_type VARCHAR(40) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    total_fare DECIMAL(12,2) NOT NULL,
    payment_reference VARCHAR(100),
    status VARCHAR(24) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_booking_user FOREIGN KEY(user_id) REFERENCES users(id),
    CONSTRAINT fk_booking_hold FOREIGN KEY(hold_id) REFERENCES seat_holds(id),
    CONSTRAINT fk_booking_train FOREIGN KEY(train_id) REFERENCES trains(id),
    CONSTRAINT fk_booking_class FOREIGN KEY(train_class_id) REFERENCES train_classes(id),
    CONSTRAINT fk_booking_origin FOREIGN KEY(origin_station_id) REFERENCES stations(id),
    CONSTRAINT fk_booking_destination FOREIGN KEY(destination_station_id) REFERENCES stations(id),
    CONSTRAINT uk_booking_hold UNIQUE(hold_id),
    CONSTRAINT uk_booking_reference UNIQUE(internal_booking_reference),
    CONSTRAINT uk_booking_user_idempotency UNIQUE(user_id, idempotency_key),
    CONSTRAINT ck_booking_status CHECK(status IN ('PENDING_PAYMENT','CONFIRMED','RAC','WAITLISTED','CANCELLED','FAILED'))
);
CREATE INDEX idx_bookings_user_created ON bookings(user_id, created_at);
CREATE INDEX idx_bookings_train_date ON bookings(train_id, journey_date);

CREATE TABLE booking_passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id VARCHAR(36) NOT NULL,
    passenger_index INTEGER NOT NULL,
    passenger_name VARCHAR(140) NOT NULL,
    age INTEGER NOT NULL,
    gender VARCHAR(10) NOT NULL,
    berth_preference VARCHAR(20) NOT NULL,
    coach_code VARCHAR(12),
    seat_number VARCHAR(12),
    berth_type VARCHAR(20),
    CONSTRAINT fk_booking_passenger_booking FOREIGN KEY(booking_id) REFERENCES bookings(id),
    CONSTRAINT uk_booking_passenger_index UNIQUE(booking_id, passenger_index),
    CONSTRAINT ck_booking_passenger_age CHECK(age BETWEEN 1 AND 125)
);

CREATE TABLE payment_transactions (
    id VARCHAR(36) PRIMARY KEY,
    booking_id VARCHAR(36) NOT NULL,
    payment_reference VARCHAR(100) NOT NULL,
    amount DECIMAL(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    processed_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_payment_booking FOREIGN KEY(booking_id) REFERENCES bookings(id),
    CONSTRAINT uk_payment_booking UNIQUE(booking_id),
    CONSTRAINT uk_payment_reference UNIQUE(payment_reference),
    CONSTRAINT ck_payment_status CHECK(status IN ('SUCCESS','FAILED'))
);
